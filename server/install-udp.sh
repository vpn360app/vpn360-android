#!/usr/bin/env bash
# VPN 360 — UDP route (Hysteria2) on an existing VPN 360 server.
#
# Adds a second way into the server that travels over UDP instead of TCP. In Russia several
# hosting networks are throttled for TCP after ~16 KB; UDP is not affected by that method.
# The current VLESS/REALITY setup and the 3x-ui panel are NOT touched.
#
# Run as root on the server:
#   bash <(curl -fsSL https://raw.githubusercontent.com/vpn360app/vpn360-android/main/server/install-udp.sh)
# Show the link again:      same command (it detects the existing install)
# New secrets (new link):   same command + --reinstall
# Remove everything:        same command + --uninstall
set -euo pipefail

PORT="${PORT:-443}"
DIR=/etc/vpn360-udp
BIN=/usr/local/bin/vpn360-hysteria
SVC=vpn360-udp
RUN_USER=vpn360udp
REL=https://github.com/apernet/hysteria/releases/latest/download

say()  { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

show_link() {
  local link; link="$(cat "$DIR/link.txt")"
  say "Enlace VPN 360 (ruta UDP). Envíalo SOLO a la persona de prueba:"
  echo
  echo "$link"
  echo
  if command -v qrencode >/dev/null 2>&1; then
    say "QR (toma una captura de pantalla y envíala):"
    qrencode -t ANSIUTF8 -m 2 "$link"
  fi
  echo "Guardado en $DIR/link.txt"
}

[ "$(id -u)" = 0 ] || fail "Ejecuta este comando como root (escribe: sudo -i)."
command -v systemctl >/dev/null || fail "Este servidor no usa systemd."

case "${1:-}" in
  --uninstall)
    say "Quitando la ruta UDP de VPN 360"
    systemctl disable --now "$SVC" 2>/dev/null || true
    rm -f "/etc/systemd/system/$SVC.service" "$BIN" /etc/sysctl.d/99-vpn360-udp.conf
    rm -rf "$DIR"
    systemctl daemon-reload
    echo "Listo. La VPN principal sigue igual."
    exit 0 ;;
  --reinstall) systemctl disable --now "$SVC" 2>/dev/null || true; rm -rf "$DIR" ;;
  "") if [ -f "$DIR/link.txt" ] && systemctl is-active --quiet "$SVC"; then
        say "Ya estaba instalado y funcionando."; show_link; exit 0
      fi ;;
  *) fail "Opción desconocida: $1" ;;
esac

say "1/7 Revisando el puerto UDP $PORT"
if ss -H -lun "sport = :$PORT" 2>/dev/null | grep -q .; then
  systemctl is-active --quiet "$SVC" && systemctl stop "$SVC"
  ss -H -lun "sport = :$PORT" | grep -q . && fail "El puerto UDP $PORT ya está en uso. Prueba con: PORT=8443 y el mismo comando."
fi
echo "Libre."

say "2/7 Descargando Hysteria2 (programa oficial, verificado)"
case "$(uname -m)" in
  x86_64|amd64) ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  *) fail "Arquitectura no soportada: $(uname -m)" ;;
esac
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
curl -fsSL --retry 3 -o "$TMP/hysteria" "$REL/hysteria-linux-$ARCH" || fail "No se pudo descargar Hysteria2."
curl -fsSL --retry 3 -o "$TMP/hashes.txt" "$REL/hashes.txt" || fail "No se pudo descargar la lista de verificación."
WANT="$(awk -v f="build/hysteria-linux-$ARCH" '$2==f{print $1}' "$TMP/hashes.txt")"
GOT="$(sha256sum "$TMP/hysteria" | awk '{print $1}')"
[ -n "$WANT" ] && [ "$WANT" = "$GOT" ] || fail "La descarga no coincide con la firma publicada. No se instaló nada."
install -m 755 "$TMP/hysteria" "$BIN"
"$BIN" version 2>/dev/null | grep -i '^version' || true

say "3/7 Generando claves y certificado"
mkdir -p "$DIR"
id "$RUN_USER" >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin "$RUN_USER"
AUTH="$(openssl rand -hex 16)"
OBFS="$(openssl rand -hex 16)"
SNI="s$(openssl rand -hex 4).net"
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 3650 \
  -subj "/CN=$SNI" -addext "subjectAltName=DNS:$SNI" \
  -keyout "$DIR/key.pem" -out "$DIR/cert.pem" >/dev/null 2>&1 || fail "No se pudo crear el certificado."
PIN="$(openssl x509 -in "$DIR/cert.pem" -noout -fingerprint -sha256 | cut -d= -f2 | tr -d ':' | tr 'A-F' 'a-f')"

cat > "$DIR/config.yaml" <<EOF
# VPN 360 — UDP route (Hysteria2). Generated by install-udp.sh
listen: :$PORT
tls:
  cert: $DIR/cert.pem
  key: $DIR/key.pem
obfs:
  type: salamander
  salamander:
    password: $OBFS
auth:
  type: password
  password: $AUTH
acl:
  inline:
    - reject(127.0.0.0/8)
    - reject(10.0.0.0/8)
    - reject(172.16.0.0/12)
    - reject(192.168.0.0/16)
    - reject(169.254.0.0/16)
    - reject(100.64.0.0/10)
    - reject(::1/128)
    - reject(fc00::/7)
    - reject(fe80::/10)
    - direct(all)
EOF
chown -R root:"$RUN_USER" "$DIR"
chmod 750 "$DIR"; chmod 640 "$DIR"/config.yaml "$DIR"/key.pem "$DIR"/cert.pem

say "4/7 Ajustando la red para UDP"
cat > /etc/sysctl.d/99-vpn360-udp.conf <<'EOF'
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
EOF
sysctl -q -p /etc/sysctl.d/99-vpn360-udp.conf || true

say "5/7 Abriendo el puerto UDP $PORT en el firewall"
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw allow "$PORT"/udp >/dev/null && echo "ufw: abierto."
elif command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
  firewall-cmd -q --permanent --add-port="$PORT"/udp && firewall-cmd -q --reload && echo "firewalld: abierto."
elif iptables -S INPUT 2>/dev/null | grep -q -- '-P INPUT DROP'; then
  iptables -I INPUT -p udp --dport "$PORT" -j ACCEPT && echo "iptables: abierto (se pierde al reiniciar; avísale a tu técnico)."
else
  echo "Sin firewall activo en el servidor: nada que abrir."
fi

say "6/7 Creando el servicio"
cat > "/etc/systemd/system/$SVC.service" <<EOF
[Unit]
Description=VPN 360 UDP route (Hysteria2)
After=network-online.target
Wants=network-online.target

[Service]
User=$RUN_USER
Group=$RUN_USER
ExecStart=$BIN server -c $DIR/config.yaml --disable-update-check
AmbientCapabilities=CAP_NET_BIND_SERVICE
CapabilityBoundingSet=CAP_NET_BIND_SERVICE
NoNewPrivileges=true
Restart=always
RestartSec=3
LimitNOFILE=65535

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable --now "$SVC" >/dev/null 2>&1
sleep 3
if ! systemctl is-active --quiet "$SVC"; then
  journalctl -u "$SVC" -n 20 --no-pager || true
  fail "El servicio no arrancó (arriba está el detalle). La VPN principal no se tocó."
fi
echo "Servicio activo."

say "7/7 Preparando el enlace"
IP="${PUBLIC_IP:-}"
if [ -z "$IP" ]; then
  IP="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')"
  case "$IP" in 10.*|192.168.*|172.1[6-9].*|172.2[0-9].*|172.3[01].*|"") IP="$(curl -fsS4 --max-time 8 https://api.ipify.org || true)" ;; esac
fi
[ -n "$IP" ] || fail "No se pudo saber la IP pública. Repite con: PUBLIC_IP=x.x.x.x y el mismo comando."
echo "hysteria2://${AUTH}@${IP}:${PORT}/?sni=${SNI}&obfs=salamander&obfs-password=${OBFS}&pinSHA256=${PIN}#VPN%20360%20UDP" > "$DIR/link.txt"
chmod 600 "$DIR/link.txt"

if ! command -v qrencode >/dev/null 2>&1 && command -v apt-get >/dev/null 2>&1; then
  timeout 120 apt-get install -y -qq qrencode >/dev/null 2>&1 || true
fi
show_link
say "Listo. La VPN principal (3x-ui) sigue funcionando igual."
